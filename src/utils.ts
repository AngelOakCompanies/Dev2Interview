/**
 * Fetch random words from a static list (no network).
 * @param count Number of words to fetch.
 * @returns Array of words.
 */
export async function fetchRandomWords(count: number = 10): Promise<string[]> {
  const n = Math.max(0, Math.floor(count));
  const words: string[] = [];
  for (let i = 0; i < n; i++) {
    const idx = Math.floor(Math.random() * WORD_LIST.length);
    words.push(WORD_LIST[idx]);
  }

  return words;
}
